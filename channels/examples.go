// ТЕОРИЯ: Fan-out / Fan-in в контексте пайплайнов
// ============================================================================
// Fan-out: один канал раздаётся множеству воркеров (распараллеливание)
// Fan-in: множество каналов собираются в один (объединение результатов)
//
// Использование в пайплайнах:
// - Можно распараллелить тяжёлый этап обработки
// - Результаты собираются обратно в один канал
// ============================================================================

// ProcessNumber обрабатывает число (симуляция тяжёлой работы)
func ProcessNumber(n int) int {
	time.Sleep(10 * time.Millisecond) // симуляция работы
	return n * n
}

// FanOutStage создаёт N воркеров для обработки данных из входного канала
func FanOutStage(in <-chan int, numWorkers int, processor func(int) int) []<-chan int {
	// ТЕОРИЯ: Fan-out - распараллеливание обработки
	// Fan-out раздаёт один канал множеству воркеров
	//
	// Как работает:
	// 1. Создаём numWorkers каналов (по одному на воркера)
	// 2. Запускаем numWorkers горутин-воркеров
	// 3. Каждый воркер читает из общего канала in (Go автоматически распределяет задачи)
	// 4. Каждый воркер обрабатывает данные через processor
	// 5. Каждый воркер отправляет результат в свой канал
	// 6. Возвращаем слайс каналов для Fan-in
	//
	// Преимущества:
	// - Параллельная обработка (несколько воркеров работают одновременно)
	// - Распределение нагрузки (Go сам распределяет задачи между воркерами)

	// TODO: создай numWorkers каналов для результатов
	outputs := make([]<-chan int, numWorkers)
	outputChannels := make([]chan int, numWorkers)
	for i := 0; i < numWorkers; i++ {
		ch := make(chan int)
		outputChannels[i] = ch
		outputs[i] = ch
	}

	// TODO: запусти numWorkers горутин
	var wg sync.WaitGroup
	for i := 0; i < numWorkers; i++ {
		wg.Add(1)
		output := outputChannels[i]
		go func() {
			defer wg.Done()
			defer close(output)
			for value := range in { // все воркеры читают из одного канала
				result := processor(value) // обрабатываем
				output <- result           // отправляем в свой канал
			}
		}()
	}

	// TODO: верни слайс каналов
	// return outputs

	return outputs
}

