// Rate limiting - ограничение скорости выполнения операций
//
// Паттерн: использовать буферизованный канал как семафор
// - Заполняем канал токенами
// - Перед операцией берём токен (читаем из канала)
// - После операции возвращаем токен (отправляем в канал)
// - Если канал пуст - операция блокируется
// ============================================================================

// RateLimiter ограничивает скорость выполнения операций
type RateLimiter struct {
	tokens chan struct{}
	ticker *time.Ticker
}

// NewRateLimiter создаёт новый rate limiter
// rate - количество операций в секунду
func NewRateLimiter(rate int) *RateLimiter {
	rl := &RateLimiter{
		tokens: make(chan struct{}, rate),                         // буфер = rate (максимум rate токенов)
		ticker: time.NewTicker(time.Second / time.Duration(rate)), // тик каждые 1/rate секунды
	}

	// ТЕОРИЯ: Rate Limiting через токены
	// Паттерн: буферизованный канал как семафор с токенами
	//
	// Как работает:
	// 1. Канал tokens заполнен токенами (структурами struct{})
	// 2. Ticker отправляет новый токен каждые 1/rate секунды
	// 3. Перед операцией берём токен из канала (читаем)
	// 4. Если канал пуст - операция блокируется (ждём токен)
	// 5. Если токен есть - операция выполняется
	//
	// Пример: rate = 5 операций/сек
	// - Ticker отправляет токен каждые 200ms (1 сек / 5)
	// - Максимум 5 токенов в канале (буфер = 5)
	// - Если все токены использованы - следующая операция ждёт

	// TODO: запусти горутину которая:
	// go func() {
	//     for range rl.ticker.C {  // каждые тик
	//         select {
	//         case rl.tokens <- struct{}{}:  // отправляем токен в канал
	//             // токен отправлен
	//         default:
	//             // канал полон (все токены уже в канале) - пропускаем
	//         }
	//     }
	// }()

	go func() {
		for range rl.ticker.C {
			select {
			case rl.tokens <- struct{}{}:
			default:
			}
		}
	}()

	return rl
}

