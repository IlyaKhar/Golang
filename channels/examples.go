// ExampleBufferedChannel демонстрирует работу с буферизованными каналами
func ExampleBufferedChannel() {
	// ТЕОРИЯ: Буферизованный канал с размером буфера 3
	// - Внутренний буфер может хранить 3 значения
	// - Отправка блокируется только когда буфер полный (все 3 места заняты)
	// - Чтение блокируется только когда буфер пустой
	ch := make(chan int, 3)

	// ТЕОРИЯ: Отправка 5 значений в канал с буфером на 3
	// Шаг 1: ch <- 1 → попадает в буфер (буфер: [1], свободно: 2)
	// Шаг 2: ch <- 2 → попадает в буфер (буфер: [1, 2], свободно: 1)
	// Шаг 3: ch <- 3 → попадает в буфер (буфер: [1, 2, 3], свободно: 0) - БУФЕР ПОЛОН!
	// Шаг 4: ch <- 4 → БЛОКИРУЕТСЯ! Ждёт пока освободится место в буфере
	// Шаг 5: ch <- 5 → тоже БЛОКИРУЕТСЯ! Ждёт освобождения места
	//
	// ВАЖНО: Если никто не читает из канала, то 4-я и 5-я отправка заблокируются НАВСЕГДА!
	// Поэтому нужно либо:
	//   а) Читать значения в другой горутине параллельно
	//   б) Сначала отправить, потом прочитать (но тогда 4-я и 5-я всё равно заблокируются)

	// РЕШЕНИЕ ПРОБЛЕМЫ БЛОКИРОВКИ:
	// Вариант 1: Отправить все значения в горутине, читать в основной функции (РЕКОМЕНДУЕТСЯ)
	// go func() {
	//     ch <- 1
	//     ch <- 2
	//     ch <- 3  // эти три отправятся без блокировки
	//     ch <- 4  // эта заблокируется, но горутина подождёт
	//     ch <- 5  // эта тоже заблокируется, но горутина подождёт
	//     close(ch)  // закрываем после отправки всех
	// }()
	//
	// for value := range ch {
	//     fmt.Printf("Прочитано: %d\n", value)
	// }

	// Вариант 2: Отправить только то, что помещается, прочитать, отправить остальное
	// ТЕОРИЯ: Чередование отправки и чтения
	// - Отправляем первые 3 значения (буфер заполняется)
	// - Читаем одно значение (освобождаем место в буфере)
	// - Отправляем следующее значение
	// - Повторяем пока все значения не отправлены
	ch <- 1
	ch <- 2
	ch <- 3                         // отправляем первые 3 (буфер полон: [1, 2, 3])
	fmt.Println("Прочитано:", <-ch) // читаем 1 (освобождаем место, буфер: [2, 3])

	ch <- 4                         // отправляем 4 (буфер: [2, 3, 4])
	fmt.Println("Прочитано:", <-ch) // читаем 2 (освобождаем место, буфер: [3, 4])

	ch <- 5   // отправляем 5 (буфер: [3, 4, 5])
	close(ch) // закрываем канал после отправки всех значений

	// ТЕОРИЯ: Чтение оставшихся значений из закрытого канала
	// - После закрытия канала можно прочитать все оставшиеся значения
	// - for range автоматически завершится когда канал закрыт и пуст
	// - Или можно использовать for с проверкой ok

	// Читаем оставшиеся значения (3, 4, 5)
	fmt.Println("Оставшиеся значения:")
	for value := range ch {
		fmt.Printf("Оставшееся значение: %d\n", value)
	}

	fmt.Println("Buffered channel example completed")
}

