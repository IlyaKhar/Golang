// ТЕОРИЯ: Пайплайны (Pipelines)
// ============================================================================
// Пайплайн - это цепочка этапов обработки данных через каналы
//
// Структура:
//   Input -> Stage1 -> Stage2 -> Stage3 -> Output
//
// Каждый этап (stage):
// - Читает данные из входного канала
// - Обрабатывает данные
// - Отправляет результаты в выходной канал
// - Закрывает выходной канал когда входной закрыт
//
// Преимущества:
// - Модульность: каждый этап независим
// - Параллелизм: этапы могут работать параллельно
// - Переиспользуемость: этапы можно комбинировать
//
// Паттерны:
// 1. Generator: генерирует данные в канал
// 2. Filter: фильтрует данные по условию
// 3. Transform: преобразует данные
// 4. Sink: потребляет данные (финальный этап)
// ============================================================================

// Generator генерирует числа от start до end и отправляет их в канал
func Generator(start, end int) <-chan int {
	out := make(chan int)

	// ТЕОРИЯ: Generator - первый этап пайплайна
	// Генератор создаёт поток данных из ничего
	//
	// Как работает:
	// 1. Создаём канал out
	// 2. Запускаем горутину которая генерирует данные
	// 3. Горутина отправляет числа в канал последовательно
	// 4. Когда все числа отправлены - закрываем канал
	// 5. Закрытие канала сигнализирует следующему этапу о завершении
	//
	// ВАЖНО: Горутина должна закрыть канал после отправки всех данных!
	// Иначе следующий этап будет ждать бесконечно

	// TODO: запусти горутину которая:
	// go func() {
	//     defer close(out)  // ОБЯЗАТЕЛЬНО закрываем канал в конце!
	//     for i := start; i <= end; i++ {
	//         out <- i  // отправляем число в канал
	//     }
	// }()
	go func() {
		defer close(out)
		for i := start; i <= end; i++ {
			out <- i
		}
	}()
	return out
}

