// ExampleMultipleOperations демонстрирует отмену нескольких операций
func ExampleMultipleOperations() {
	// ТЕОРИЯ: Отмена нескольких операций
	// - Один контекст может координировать несколько операций
	// - Когда контекст отменяется - все операции прерываются
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	var wg sync.WaitGroup

	// ТЕОРИЯ: Отмена нескольких операций одним контекстом
	// - Один контекст может координировать несколько независимых операций
	// - Когда контекст отменяется - ВСЕ операции прерываются одновременно
	// - Это позволяет остановить все операции одним действием
	//
	// ПРИМЕР: Обработка нескольких файлов параллельно
	// - Каждый файл обрабатывается в отдельной горутине
	// - Все горутины используют один контекст
	// - Если нужно остановить обработку - отменяем контекст
	// - Все горутины одновременно прекратят работу

	// ТЕОРИЯ: Запускаем несколько независимых операций
	// - Каждая операция выполняется в отдельной горутине
	// - Все операции используют один контекст
	// - Когда контекст отменяется - все операции прерываются
	numOperations := 5
	for i := 1; i <= numOperations; i++ {
		wg.Add(1)
		operationID := i

		go func(id int) {
			defer wg.Done()

			// ТЕОРИЯ: Операция выполняет работу
			// - Проверяет ctx.Done() в цикле
			// - Если контекст отменён - прекращает работу
			fmt.Printf("Операция %d: начинаем работу\n", id)

			for j := 0; j < 20; j++ {
				select {
				case <-ctx.Done():
					// ТЕОРИЯ: Контекст отменён - операция прекращает работу
					fmt.Printf("Операция %d: работа прервана на шаге %d: %v\n", id, j, ctx.Err())
					return
				default:
					// ТЕОРИЯ: Контекст активен - продолжаем работу
					// Имитируем работу операции
					time.Sleep(100 * time.Millisecond)
				}
			}
			fmt.Printf("Операция %d: работа завершена успешно\n", id)
		}(operationID)
	}

	// ТЕОРИЯ: Отменяем контекст через некоторое время
	// - Это прервёт все операции одновременно
	// - Все горутины увидят ctx.Done() и прекратят работу
	go func() {
		time.Sleep(500 * time.Millisecond)
		fmt.Println("Отменяем контекст - все операции должны прекратиться")
		cancel() // Отменяем контекст - все операции прервутся
	}()

	// ТЕОРИЯ: Ожидаем завершения всех операций
	// - wg.Wait() блокируется пока все горутины не завершатся
	// - Горутины завершатся либо по завершении работы, либо по отмене контекста
	wg.Wait()
	fmt.Println("Multiple operations example completed")
}

// ExampleGracefulShutdown демонстрирует грациозное завершение с контекстом
func ExampleGracefulShutdown() {
	// ТЕОРИЯ: Грациозное завершение
	// - Используется для корректного завершения сервера
	// - Даёт время на завершение текущих запросов
	// - После таймаута - принудительное завершение
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	// ТЕОРИЯ: Graceful shutdown (грациозное завершение)
	// - Используется для корректного завершения сервера
	// - Даёт время на завершение текущих запросов
	// - После таймаута - принудительное завершение
	//
	// ПРОЦЕСС GRACEFUL SHUTDOWN:
	// 1. Остановить приём новых запросов
	// 2. Дождаться завершения текущих запросов (или таймаута)
	// 3. Закрыть соединения и освободить ресурсы
	// 4. Завершить работу сервера

	fmt.Println("Начинаем graceful shutdown...")

	// ТЕОРИЯ: Имитация сервера с активными запросами
	// - В реальном приложении здесь был бы HTTP сервер
	// - Сервер обрабатывает несколько запросов одновременно
	var serverWg sync.WaitGroup
	activeRequests := 5

	// ТЕОРИЯ: Шаг 1: Остановить приём новых запросов
	// - В реальном приложении здесь был бы вызов srv.Shutdown(ctx)
	// - Сервер перестанет принимать новые подключения
	fmt.Println("1. Останавливаем приём новых запросов...")

	// ТЕОРИЯ: Шаг 2: Дождаться завершения текущих запросов
	// - Запускаем горутины которые имитируют обработку запросов
	// - Все запросы используют контекст для отслеживания отмены
	for i := 1; i <= activeRequests; i++ {
		serverWg.Add(1)
		requestID := i

		go func(id int) {
			defer serverWg.Done()

			// ТЕОРИЯ: Имитация обработки запроса
			// - Запрос проверяет ctx.Done() во время обработки
			// - Если контекст отменён - запрос должен завершиться грациозно
			fmt.Printf("Запрос %d: начинаем обработку\n", id)

			// Имитируем обработку запроса (может занять разное время)
			processingTime := time.Duration(200+id*100) * time.Millisecond
			done := make(chan struct{})

			go func() {
				time.Sleep(processingTime)
				close(done)
			}()

			select {
			case <-done:
				// ТЕОРИЯ: Запрос обработан успешно
				fmt.Printf("Запрос %d: обработка завершена успешно\n", id)
			case <-ctx.Done():
				// ТЕОРИЯ: Контекст отменён - запрос прерван
				// - В реальном приложении здесь была бы очистка ресурсов
				fmt.Printf("Запрос %d: обработка прервана (таймаут shutdown)\n", id)
			}
		}(requestID)
	}

	// ТЕОРИЯ: Шаг 3: Ожидаем завершения всех запросов или таймаута
	// - serverWg.Wait() ждёт завершения всех запросов
	// - Но контекст имеет таймаут - если запросы не завершатся за это время, продолжаем
	done := make(chan struct{})
	go func() {
		serverWg.Wait()
		close(done)
	}()

	select {
	case <-done:
		// ТЕОРИЯ: Все запросы завершены успешно
		fmt.Println("2. Все запросы завершены успешно")
	case <-ctx.Done():
		// ТЕОРИЯ: Таймаут истёк - некоторые запросы могут быть не завершены
		fmt.Println("2. Таймаут истёк - некоторые запросы могут быть не завершены")
	}

	// ТЕОРИЯ: Шаг 4: Закрыть соединения и освободить ресурсы
	// - В реальном приложении здесь была бы очистка ресурсов
	// - Например: закрытие соединений с БД, очистка кэша, сохранение состояния
	fmt.Println("3. Закрываем соединения и освобождаем ресурсы...")
	time.Sleep(100 * time.Millisecond) // Имитация очистки ресурсов

	fmt.Println("4. Сервер завершён грациозно")
	fmt.Println("Graceful shutdown example completed")
}

