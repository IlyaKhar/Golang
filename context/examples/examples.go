// ============================================================================
// ТЕОРИЯ: Context в Go - это механизм для передачи сигналов отмены, таймаутов
// и значений между горутинами и функциями
// ============================================================================
//
// ЗАЧЕМ НУЖЕН CONTEXT:
// 1. Отмена операций - когда нужно прервать долгую операцию
// 2. Таймауты - ограничить время выполнения операции
// 3. Дедлайны - завершить операцию до определённого времени
// 4. Передача значений - передать request-scoped данные (например, user ID)
//
// КЛЮЧЕВЫЕ ПРИНЦИПЫ:
// - Context НЕИЗМЕНЯЕМ (immutable) - нельзя изменить существующий контекст
// - Context передаётся ПЕРВЫМ параметром функции (ctx context.Context)
// - Context должен быть передан ВСЕМ функциям, которые могут быть отменены
// - Context создаётся в верхнем слое (HTTP handler, main) и передаётся вниз
//
// PROPAGATE CANCELLATION (Распространение отмены):
// - Когда контекст отменяется на верхнем уровне, все дочерние операции
//   автоматически получают сигнал об отмене через ctx.Done()
// - Это позволяет грациозно завершить все операции в цепочке вызовов
//
// ============================================================================

// ExampleBasicContext демонстрирует базовое использование context
func ExampleBasicContext() {
	// ТЕОРИЯ: context.Background() - корневой контекст
	// - Используется в main функции, тестах, на верхнем уровне
	// - Никогда не отменяется, не имеет таймаута
	// - Это "пустой" контекст, от которого создаются все остальные
	ctx := context.Background()

	// ТЕОРИЯ: context.TODO() - контекст-заглушка
	// - Используется когда не уверен какой контекст использовать
	// - Сигнализирует что контекст нужно будет заменить позже
	// - В продакшене лучше использовать Background() или передавать реальный контекст
	_ = context.TODO()

	// ТЕОРИЯ: Проверка контекста
	// - ctx.Done() возвращает канал, который закрывается при отмене
	// - ctx.Err() возвращает ошибку (context.Canceled или context.DeadlineExceeded)
	// - ctx.Value(key) возвращает значение по ключу (если было установлено)
	select {
	case <-ctx.Done():
		fmt.Println("Контекст отменён")
	default:
		fmt.Println("Контекст активен")
	}

	fmt.Println("Basic context example completed")
}

// ExampleWithCancel демонстрирует отмену контекста вручную
func ExampleWithCancel() {
	// ТЕОРИЯ: context.WithCancel(parent) создаёт новый контекст с функцией отмены
	// - Возвращает контекст и функцию cancel()
	// - Когда вызывается cancel(), контекст отменяется
	// - Все дочерние контексты тоже отменяются (propagation)
	//
	// ЖИЗНЕННЫЙ ПРИМЕР:
	// Представь что ты заказал пиццу. Пока она готовится, ты можешь:
	// 1. Дождаться пиццу (операция завершилась)
	// 2. Отменить заказ (вызвать cancel()) - пицца не нужна
	// 3. Повар (горутина) видит отмену и прекращает готовить
	ctx, cancel := context.WithCancel(context.Background())

	var wg sync.WaitGroup

	// Запускаем горутину которая "готовит пиццу"
	wg.Add(1)
	go func() {
		defer wg.Done()
		for i := 0; i < 10; i++ {
			select {
			case <-ctx.Done():
				// ТЕОРИЯ: Контекст отменён - прекращаем работу
				// - Это позволяет грациозно завершить операцию
				// - Можно освободить ресурсы, закрыть соединения и т.д.
				fmt.Printf("Работа прервана на шаге %d: %v\n", i, ctx.Err())
				return
			default:
				// Имитируем работу
				fmt.Printf("Работаем... шаг %d\n", i)
				time.Sleep(100 * time.Millisecond)
			}
		}
		fmt.Println("Работа завершена успешно")
	}()

	// ТЕОРИЯ: Отменяем контекст через 300ms
	// - Это прервёт работу горутины
	// - Горутина увидит ctx.Done() и завершится
	time.Sleep(300 * time.Millisecond)
	cancel() // ОТМЕНЯЕМ контекст

	wg.Wait()
	fmt.Println("WithCancel example completed")
}

// ExampleWithTimeout демонстрирует контекст с таймаутом
func ExampleWithTimeout() {
	// ТЕОРИЯ: context.WithTimeout(parent, duration) создаёт контекст с таймаутом
	// - Автоматически отменяется через указанное время
	// - Если операция не завершилась за это время - она прерывается
	//
	// ЖИЗНЕННЫЙ ПРИМЕР:
	// Ты заказал такси и договорились что оно приедет за 5 минут.
	// Если через 5 минут такси не приехало - ты вызываешь другое.
	// Таймаут = 5 минут, операция = ожидание такси
	ctx, cancel := context.WithTimeout(context.Background(), 500*time.Millisecond)
	defer cancel() // ВАЖНО: всегда вызывать cancel() для освобождения ресурсов

	// Имитируем долгую операцию
	done := make(chan bool)
	go func() {
		time.Sleep(1 * time.Second) // Операция занимает 1 секунду
		done <- true
	}()

	select {
	case <-done:
		fmt.Println("Операция завершена успешно")
	case <-ctx.Done():
		// ТЕОРИЯ: Таймаут истёк - операция прервана
		// - ctx.Err() вернёт context.DeadlineExceeded
		fmt.Printf("Операция прервана по таймауту: %v\n", ctx.Err())
	}

	fmt.Println("WithTimeout example completed")
}

// ExampleWithDeadline демонстрирует контекст с дедлайном
func ExampleWithDeadline() {
	// ТЕОРИЯ: context.WithDeadline(parent, time) создаёт контекст с дедлайном
	// - Отменяется в определённый момент времени (дедлайн)
	// - Похож на WithTimeout, но указывается конкретное время, а не длительность
	//
	// РАЗНИЦА МЕЖДУ TIMEOUT И DEADLINE:
	// - Timeout: "выполни за 5 секунд" (относительное время)
	// - Deadline: "выполни до 15:30" (абсолютное время)
	deadline := time.Now().Add(500 * time.Millisecond)
	ctx, cancel := context.WithDeadline(context.Background(), deadline)
	defer cancel()

	// ТЕОРИЯ: Дедлайн работает так же как таймаут, но с абсолютным временем
	// - deadline = время сейчас + 500ms (например, 14:30:00.500)
	// - Если операция не завершится до этого времени - она отменится
	// - Можно использовать для операций которые должны завершиться до определённого времени

	// Создаём канал для сигнала завершения операции
	done := make(chan bool, 1)

	// ТЕОРИЯ: Запускаем горутину которая выполняет долгую операцию
	// - Операция занимает 1 секунду
	// - Но дедлайн через 500ms
	// - Поэтому операция будет прервана по дедлайну
	go func() {
		// Имитируем долгую операцию (1 секунда)
		time.Sleep(1 * time.Second)
		// Отправляем сигнал о завершении
		done <- true
	}()

	// ТЕОРИЯ: Используем select для ожидания двух событий:
	// 1. Завершение операции (done)
	// 2. Отмена контекста по дедлайну (ctx.Done())
	// - select выберет первый доступный канал
	// - Если дедлайн истечёт раньше - выберется ctx.Done()
	select {
	case <-done:
		// Операция завершилась успешно (но в нашем случае это не произойдёт, т.к. дедлайн истечёт раньше)
		fmt.Println("Операция завершена успешно")
	case <-ctx.Done():
		// ТЕОРИЯ: Дедлайн истёк - контекст отменён
		// - ctx.Err() вернёт context.DeadlineExceeded
		// - Это означает что операция не успела завершиться до дедлайна
		fmt.Printf("Операция прервана по дедлайну: %v\n", ctx.Err())
	}

	fmt.Println("WithDeadline example completed")
}

// ExampleWithValue демонстрирует передачу значений через контекст
func ExampleWithValue() {
	// ТЕОРИЯ: context.WithValue(parent, key, value) добавляет значение в контекст
	// - Значения должны быть request-scoped (привязаны к запросу)
	// - НЕ использовать для передачи опциональных параметров!
	// - Ключи должны быть уникального типа (не string напрямую!)
	//
	// КОГДА ИСПОЛЬЗОВАТЬ:
	// - User ID из токена аутентификации
	// - Request ID для трейсинга
	// - Локализация пользователя
	//
	// КОГДА НЕ ИСПОЛЬЗОВАТЬ:
	// - Функциональные параметры (передавай явно!)
	// - Структуры данных (используй параметры функции)
	type userIDKey string
	type requestIDKey string

	const uidKey userIDKey = "userID"
	const reqIDKey requestIDKey = "requestID"

	// Создаём контекст с значениями
	ctx := context.WithValue(context.Background(), uidKey, "12345")
	ctx = context.WithValue(ctx, reqIDKey, "req-abc-123")

	// ТЕОРИЯ: Получение значений из контекста
	// - ctx.Value(key) возвращает значение по ключу
	// - Если ключ не найден - возвращает nil
	// - Значения должны быть request-scoped (привязаны к запросу)
	//
	// ВАЖНО: Типы ключей должны быть уникальными!
	// - Не используй строки напрямую как ключи
	// - Создавай отдельные типы для ключей (type userIDKey string)
	// - Это предотвращает коллизии ключей из разных пакетов

	// Получаем значения из контекста
	userID := ctx.Value(uidKey)
	requestID := ctx.Value(reqIDKey)

	// ТЕОРИЯ: Проверка значений
	// - ctx.Value() возвращает interface{}, нужно привести к нужному типу
	// - Всегда проверяй на nil перед использованием
	// - Используй type assertion для приведения типа
	if userID != nil {
		// Приводим к строке (т.к. мы сохранили строку)
		if uid, ok := userID.(string); ok {
			fmt.Printf("User ID: %s\n", uid)
		}
	}

	if requestID != nil {
		if reqID, ok := requestID.(string); ok {
			fmt.Printf("Request ID: %s\n", reqID)
		}
	}

	fmt.Println("WithValue example completed")
}

// ExamplePropagateCancellation демонстрирует распространение отмены
func ExamplePropagateCancellation() {
	// ТЕОРИЯ: Propagation Cancellation - это автоматическая передача сигнала отмены
	// от родительского контекста ко всем дочерним операциям
	//
	// КАК ЭТО РАБОТАЕТ:
	// 1. Создаёшь контекст на верхнем уровне (например, в HTTP handler)
	// 2. Передаёшь его во все функции в цепочке вызовов
	// 3. Когда контекст отменяется - ВСЕ операции в цепочке получают сигнал
	//
	// ПРЕИМУЩЕСТВА:
	// - Не нужно передавать каналы отмены вручную
	// - Автоматическая очистка ресурсов
	// - Предсказуемое поведение при отмене
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	// ТЕОРИЯ: Propagation Cancellation - это ключевая особенность context
	// - Когда родительский контекст отменяется, ВСЕ дочерние контексты тоже отменяются
	// - Это происходит автоматически через ctx.Done()
	// - Не нужно передавать каналы отмены вручную
	//
	// Структура вызовов:
	// ExamplePropagateCancellation (родительский контекст)
	//   -> processData(ctx, data) (тот же контекст)
	//       -> saveToDB(ctx, data) (тот же контекст)
	//       -> sendNotification(ctx, data) (тот же контекст)
	//
	// Когда cancel() вызывается в ExamplePropagateCancellation:
	// - processData увидит ctx.Done() и вернёт ошибку
	// - saveToDB увидит ctx.Done() и вернёт ошибку
	// - sendNotification увидит ctx.Done() и вернёт ошибку
	// - Все функции в цепочке автоматически прекратят работу

	// Запускаем обработку данных
	err := processData(ctx, "test data")
	if err != nil {
		// ТЕОРИЯ: Если контекст отменён, все функции вернут ошибку
		// - err будет context.Canceled если мы вызвали cancel()
		// - err будет context.DeadlineExceeded если истёк таймаут
		fmt.Printf("Ошибка обработки: %v\n", err)
	} else {
		fmt.Println("Данные обработаны успешно")
	}

	// ТЕОРИЯ: Демонстрация отмены
	// - Отменяем контекст через 100ms
	// - Это прервёт все операции в цепочке
	go func() {
		time.Sleep(100 * time.Millisecond)
		cancel() // Отменяем контекст - все операции прекратятся
		fmt.Println("Контекст отменён - все операции должны прекратиться")
	}()

	fmt.Println("Propagate cancellation example completed")
}

// processData обрабатывает данные с поддержкой отмены
func processData(ctx context.Context, data string) error {
	// ТЕОРИЯ: Контекст передаётся вниз по цепочке вызовов
	// - Каждая функция должна проверять ctx.Done()
	// - Если контекст отменён - функция должна вернуть ошибку
	select {
	case <-ctx.Done():
		return ctx.Err()
	default:
		// Продолжаем обработку
	}

	// ТЕОРИЯ: Передача контекста вниз по цепочке вызовов
	// - Каждая функция получает тот же контекст
	// - Если контекст отменён - все функции должны проверить это
	// - Функции должны вернуть ошибку если контекст отменён

	fmt.Printf("Обрабатываем данные: %s\n", data)

	// ТЕОРИЯ: Сохраняем данные в БД
	// - Передаём контекст в saveToDB
	// - Если контекст отменён - saveToDB вернёт ошибку
	err := saveToDB(ctx, data)
	if err != nil {
		// ТЕОРИЯ: Если контекст отменён, saveToDB вернёт ctx.Err()
		// - Это может быть context.Canceled или context.DeadlineExceeded
		return err
	}

	// ТЕОРИЯ: Отправляем уведомление
	// - Передаём контекст в sendNotification
	// - Если контекст отменён - sendNotification вернёт ошибку
	err = sendNotification(ctx, data)
	if err != nil {
		return err
	}

	fmt.Println("Данные обработаны успешно")
	return nil
}

// saveToDB сохраняет данные в БД с поддержкой отмены
func saveToDB(ctx context.Context, data string) error {
	// ТЕОРИЯ: Проверка контекста перед операцией
	// - Проверяем ctx.Done() чтобы узнать не отменён ли контекст
	// - Если контекст отменён - сразу возвращаем ошибку
	// - Это позволяет не начинать операцию если она уже не нужна
	select {
	case <-ctx.Done():
		// ТЕОРИЯ: Контекст отменён - операция не нужна
		// - Возвращаем ошибку из контекста
		// - Это может быть context.Canceled или context.DeadlineExceeded
		fmt.Println("saveToDB: контекст отменён, прекращаем сохранение")
		return ctx.Err()
	default:
		// Контекст активен - продолжаем операцию
	}

	// ТЕОРИЯ: Имитация сохранения в БД
	// - В реальном приложении здесь был бы запрос к БД
	// - Например: db.ExecContext(ctx, "INSERT INTO ...", data)
	// - Если контекст отменяется во время операции - запрос прервётся
	fmt.Printf("saveToDB: сохраняем данные '%s' в БД...\n", data)

	// Имитируем долгую операцию сохранения
	// ТЕОРИЯ: В реальном приложении нужно проверять контекст во время операции
	// - Если операция долгая (например, загрузка большого файла)
	// - Нужно периодически проверять ctx.Done() в цикле
	for i := 0; i < 5; i++ {
		select {
		case <-ctx.Done():
			// Контекст отменён во время операции
			fmt.Printf("saveToDB: операция прервана на шаге %d\n", i)
			return ctx.Err()
		default:
			// Имитируем работу
			time.Sleep(50 * time.Millisecond)
		}
	}

	fmt.Println("saveToDB: данные сохранены успешно")
	return nil
}

// sendNotification отправляет уведомление с поддержкой отмены
func sendNotification(ctx context.Context, data string) error {
	// ТЕОРИЯ: Проверка контекста перед отправкой
	// - Аналогично saveToDB, проверяем контекст перед началом операции
	// - Если контекст отменён - не начинаем отправку
	select {
	case <-ctx.Done():
		fmt.Println("sendNotification: контекст отменён, прекращаем отправку")
		return ctx.Err()
	default:
		// Контекст активен - продолжаем
	}

	// ТЕОРИЯ: Имитация отправки уведомления
	// - В реальном приложении здесь был бы HTTP запрос или отправка в очередь
	// - Например: http.PostContext(ctx, url, body)
	// - Контекст автоматически отменит запрос если он отменён
	fmt.Printf("sendNotification: отправляем уведомление для данных '%s'...\n", data)

	// Имитируем отправку уведомления
	// ТЕОРИЯ: Проверяем контекст во время операции
	// - Если операция может занять время - проверяем контекст периодически
	for i := 0; i < 3; i++ {
		select {
		case <-ctx.Done():
			fmt.Printf("sendNotification: операция прервана на шаге %d\n", i)
			return ctx.Err()
		default:
			time.Sleep(50 * time.Millisecond)
		}
	}

	fmt.Println("sendNotification: уведомление отправлено успешно")
	return nil
}

// ExampleContextInGoroutines демонстрирует использование контекста в горутинах
func ExampleContextInGoroutines() {
	// ТЕОРИЯ: Контекст в горутинах
	// - Каждая горутина должна получать свой контекст
	// - НЕ передавать один контекст в несколько горутин если они независимы
	// - Использовать контекст для координации горутин
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
	defer cancel()

	var wg sync.WaitGroup

	// ТЕОРИЯ: Контекст в горутинах
	// - Один контекст может координировать несколько горутин
	// - Когда контекст отменяется - ВСЕ горутины получают сигнал
	// - Это позволяет остановить все горутины одновременно
	//
	// ВАЖНО: Передавай контекст в горутины, а не создавай новый!
	// - Все горутины должны использовать один и тот же контекст
	// - Это обеспечивает синхронизированную отмену всех операций

	// ТЕОРИЯ: Запускаем 3 горутины для параллельной обработки
	// - Каждая горутина получает тот же контекст
	// - Когда контекст отменяется (таймаут 2 секунды) - все горутины останавливаются
	for i := 1; i <= 3; i++ {
		wg.Add(1)
		workerID := i // Важно: захватываем i в локальную переменную

		go func(id int) {
			defer wg.Done()

			// ТЕОРИЯ: Горутина выполняет долгую операцию
			// - Проверяет ctx.Done() в цикле
			// - Если контекст отменён - прекращает работу
			for j := 0; j < 10; j++ {
				select {
				case <-ctx.Done():
					// ТЕОРИЯ: Контекст отменён - горутина прекращает работу
					// - Это может произойти из-за таймаута или явной отмены
					fmt.Printf("Worker %d: работа прервана на шаге %d: %v\n", id, j, ctx.Err())
					return
				default:
					// ТЕОРИЯ: Контекст активен - продолжаем работу
					fmt.Printf("Worker %d: выполняет работу, шаг %d\n", id, j)
					time.Sleep(200 * time.Millisecond)
				}
			}
			fmt.Printf("Worker %d: работа завершена успешно\n", id)
		}(workerID)
	}

	// ТЕОРИЯ: Ожидаем завершения всех горутин
	// - wg.Wait() блокируется пока все горутины не завершатся
	// - Горутины завершатся либо по завершении работы, либо по отмене контекста
	wg.Wait()
	fmt.Println("Context in goroutines example completed")
}

// ExampleContextInHTTPClient демонстрирует использование контекста в HTTP клиенте
func ExampleContextInHTTPClient() {
	// ТЕОРИЯ: Контекст в HTTP запросах
	// - http.NewRequestWithContext(ctx, method, url, body) создаёт запрос с контекстом
	// - Если контекст отменяется - запрос прерывается
	// - Это позволяет отменить долгие запросы
	ctx, cancel := context.WithTimeout(context.Background(), 1*time.Second)
	defer cancel()

	// ТЕОРИЯ: HTTP запрос с контекстом
	// - http.NewRequestWithContext(ctx, method, url, body) создаёт запрос с контекстом
	// - Если контекст отменяется - HTTP запрос автоматически прерывается
	// - Это позволяет отменить долгие запросы без ожидания таймаута сервера
	//
	// ПРИМЕР: Запрос к httpbin.org/delay/2 задержит ответ на 2 секунды
	// - Но наш контекст имеет таймаут 1 секунду
	// - Поэтому запрос будет прерван через 1 секунду

	// ТЕОРИЯ: Создаём HTTP запрос с контекстом
	// - Контекст передаётся в запрос
	// - Если контекст отменяется - запрос отменяется
	req, err := http.NewRequestWithContext(ctx, "GET", "https://httpbin.org/delay/2", nil)
	if err != nil {
		fmt.Printf("Ошибка создания запроса: %v\n", err)
		return
	}

	// ТЕОРИЯ: Выполняем HTTP запрос
	// - http.DefaultClient.Do(req) выполняет запрос
	// - Если контекст отменяется во время запроса - Do() вернёт ошибку
	// - Ошибка будет содержать context.DeadlineExceeded или context.Canceled
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		// ТЕОРИЯ: Обработка ошибок HTTP запроса
		// - Если контекст отменён - err будет содержать ошибку контекста
		// - Проверяем является ли ошибка ошибкой контекста
		if ctx.Err() == context.DeadlineExceeded {
			fmt.Printf("Запрос прерван по таймауту: %v\n", err)
		} else if ctx.Err() == context.Canceled {
			fmt.Printf("Запрос отменён: %v\n", err)
		} else {
			fmt.Printf("Ошибка выполнения запроса: %v\n", err)
		}
		return
	}
	defer resp.Body.Close()

	// ТЕОРИЯ: Обработка успешного ответа
	// - Если запрос успешен - обрабатываем ответ
	fmt.Printf("Запрос выполнен успешно, статус: %d\n", resp.StatusCode)

	fmt.Println("Context in HTTP client example completed")
}

