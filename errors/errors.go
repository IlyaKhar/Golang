// ExampleMultipleErrors демонстрирует работу с несколькими ошибками
func ExampleMultipleErrors() {
	// ТЕОРИЯ: Несколько ошибок
	// - Можно собирать несколько ошибок в одну
	// - Используй errors.Join() для объединения ошибок
	// - Или создай свой тип для множественных ошибок

	// ТЕОРИЯ: Объединение нескольких ошибок
	// - errors.Join() объединяет несколько ошибок в одну
	// - Полезно когда нужно вернуть несколько ошибок одновременно
	// - errors.Is() и errors.As() проверяют все объединённые ошибки
	//
	// СИНТАКСИС:
	// combinedErr := errors.Join(err1, err2, err3)

	// Создаём несколько ошибок
	err1 := errors.New("ошибка 1: файл не найден")
	err2 := errors.New("ошибка 2: недостаточно прав")
	err3 := fmt.Errorf("ошибка 3: %w", io.EOF)

	// ТЕОРИЯ: Объединение ошибок через errors.Join()
	// - Объединяет несколько ошибок в одну
	// - Все ошибки сохраняются и доступны для проверки
	combinedErr := errors.Join(err1, err2, err3)

	fmt.Printf("Объединённая ошибка: %v\n", combinedErr)

	// ТЕОРИЯ: Проверка ошибок в объединённой ошибке
	// - errors.Is() проверяет все объединённые ошибки
	// - Найдёт io.EOF даже если он внутри одной из ошибок
	if errors.Is(combinedErr, io.EOF) {
		fmt.Println("Найдена ошибка io.EOF в объединённой ошибке")
	}

	// ТЕОРИЯ: Проверка конкретных ошибок
	// - Можно проверить любую из объединённых ошибок
	if errors.Is(combinedErr, err1) {
		fmt.Println("Найдена ошибка err1 в объединённой ошибке")
	}

	fmt.Println("Multiple errors example completed")
}

