// ValidationError - пример своего типа ошибки для демонстрации
// ТЕОРИЯ: Создание своего типа ошибки на уровне пакета
// - Методы можно определять только на уровне пакета
// - Структура с полями для структурированной информации
type ValidationError struct {
	Field   string
	Value   interface{}
	Message string
}

// Error реализует интерфейс error
// ТЕОРИЯ: Метод Error() возвращает строковое представление ошибки
func (e *ValidationError) Error() string {
	return fmt.Sprintf("валидация поля '%s' со значением '%v': %s", e.Field, e.Value, e.Message)
}

// ============================================================================
//
// В Go ошибки - это обычные значения, которые возвращаются из функций
// - Ошибка это интерфейс: type error interface { Error() string }
// - Функции возвращают ошибку как последнее значение: func do() (result, error)
// - Если ошибки нет - возвращаем nil
//
// ОСНОВНЫЕ ПРИНЦИПЫ:
// 1. Всегда проверяй ошибки - не игнорируй их!
// 2. Оборачивай ошибки с контекстом - fmt.Errorf("операция: %w", err)
// 3. Используй errors.Is() для проверки конкретной ошибки
// 4. Используй errors.As() для извлечения типа ошибки
// 5. Создавай свои типы ошибок для важных случаев
//
// ERROR WRAPPING (Обёртывание ошибок):
// - fmt.Errorf с %w оборачивает ошибку, сохраняя цепочку
// - errors.Is() проверяет ошибку в цепочке
// - errors.As() извлекает тип из цепочки
// - Это позволяет добавлять контекст, не теряя исходную ошибку
//
// ============================================================================

