// ExampleErrorWrapping демонстрирует обёртывание ошибок
func ExampleErrorWrapping() {
	// ТЕОРИЯ: Error Wrapping (обёртывание ошибок)
	// - fmt.Errorf с %w оборачивает ошибку, сохраняя цепочку
	// - Это позволяет добавлять контекст к ошибке
	// - Исходная ошибка сохраняется и доступна через errors.Unwrap()
	//
	// СИНТАКСИС:
	// wrappedErr := fmt.Errorf("контекст: %w", originalErr)
	// - %w - это специальный глагол для обёртывания ошибок
	// - originalErr будет доступен через errors.Unwrap(wrappedErr)

	// Создаём исходную ошибку
	originalErr := errors.New("файл не найден")

	// ТЕОРИЯ: Оборачиваем ошибку с контекстом
	// - Добавляем информацию о том, где произошла ошибка
	// - Исходная ошибка сохраняется в цепочке
	wrappedErr := fmt.Errorf("не удалось открыть файл: %w", originalErr)

	fmt.Printf("Оригинальная ошибка: %v\n", originalErr)
	fmt.Printf("Обёрнутая ошибка: %v\n", wrappedErr)

	// ТЕОРИЯ: errors.Unwrap() извлекает исходную ошибку
	// - Возвращает ошибку из цепочки
	// - Если ошибка не обёрнута - возвращает nil
	unwrapped := errors.Unwrap(wrappedErr)
	if unwrapped != nil {
		fmt.Printf("Распакованная ошибка: %v\n", unwrapped)
	}

	// ТЕОРИЯ: Создание цепочки ошибок
	// - Можно оборачивать ошибку несколько раз
	// - Каждое обёртывание добавляет новый контекст
	// - errors.Unwrap() извлекает ошибку на один уровень вверх

	// Создаём цепочку из 3 ошибок
	// Уровень 1: исходная ошибка
	err1 := errors.New("файл не найден")

	// Уровень 2: добавляем контекст "открытие файла"
	err2 := fmt.Errorf("не удалось открыть файл: %w", err1)

	// Уровень 3: добавляем контекст "обработка данных"
	err3 := fmt.Errorf("обработка данных: %w", err2)

	fmt.Printf("Ошибка уровня 3: %v\n", err3)

	// ТЕОРИЯ: Распаковка цепочки ошибок
	// - errors.Unwrap() извлекает ошибку на один уровень вверх
	// - Можно вызывать несколько раз для распаковки всей цепочки
	fmt.Println("\nРаспаковка цепочки ошибок:")
	currentErr := err3
	level := 3
	for currentErr != nil {
		fmt.Printf("Уровень %d: %v\n", level, currentErr)
		currentErr = errors.Unwrap(currentErr)
		level--
	}

	fmt.Println("Error wrapping example completed")
}

// ExampleErrorsIs демонстрирует использование errors.Is()
func ExampleErrorsIs() {
	// ТЕОРИЯ: errors.Is(err, target) проверяет ошибку в цепочке
	// - Проверяет ошибку и все обёрнутые ошибки в цепочке
	// - Возвращает true если найдена ошибка target
	// - Полезно для проверки конкретных ошибок (например, io.EOF)
	//
	// СИНТАКСИС:
	// if errors.Is(err, targetErr) {
	//     // обработай конкретную ошибку
	// }

	// Создаём ошибку с io.EOF внутри
	err := fmt.Errorf("операция: %w", io.EOF)

	// ТЕОРИЯ: Проверка ошибки в цепочке
	// - errors.Is() проверяет err и все обёрнутые ошибки
	// - Найдёт io.EOF даже если он обёрнут
	if errors.Is(err, io.EOF) {
		fmt.Println("Найдена ошибка io.EOF в цепочке")
	}

	// ТЕОРИЯ: Проверка ошибки в глубокой цепочке
	// - errors.Is() проверяет всю цепочку ошибок
	// - Найдёт io.EOF даже если он обёрнут несколько раз

	// Создаём глубокую цепочку ошибок с io.EOF внутри
	deepErr := fmt.Errorf("уровень 3: %w",
		fmt.Errorf("уровень 2: %w",
			fmt.Errorf("уровень 1: %w", io.EOF)))

	// ТЕОРИЯ: errors.Is() найдёт io.EOF в цепочке
	// - Проверяет все уровни обёртывания
	// - Возвращает true если найдена ошибка target
	if errors.Is(deepErr, io.EOF) {
		fmt.Println("Найдена ошибка io.EOF в глубокой цепочке")
	}

	// ТЕОРИЯ: Создание своей ошибки для проверки
	// - Создаём переменную с ошибкой
	// - Используем errors.Is() для проверки в цепочке
	myErr := errors.New("моя ошибка")
	wrappedMyErr := fmt.Errorf("контекст: %w", myErr)

	if errors.Is(wrappedMyErr, myErr) {
		fmt.Println("Найдена моя ошибка в цепочке")
	}

	fmt.Println("Errors.Is example completed")
}

// ExampleErrorsAs демонстрирует использование errors.As()
func ExampleErrorsAs() {
	// ТЕОРИЯ: errors.As(err, target) извлекает тип из цепочки
	// - Проверяет ошибку и все обёрнутые ошибки
	// - Если найдена ошибка нужного типа - записывает в target
	// - Возвращает true если тип найден
	// - Полезно для извлечения структурированных ошибок
	//
	// СИНТАКСИС:
	// var targetErr *MyError
	// if errors.As(err, &targetErr) {
	//     // используй targetErr
	// }

	// ТЕОРИЯ: Создание ошибки своего типа
	// - Используем ValidationError определённый на уровне пакета
	// - Создаём экземпляр структуры
	validationErr := &ValidationError{
		Field:   "email",
		Value:   "invalid@",
		Message: "неверный формат",
	}

	// Оборачиваем ошибку с контекстом
	// ТЕОРИЯ: errors.As() работает с ошибками которые реализуют интерфейс error
	// - ValidationError реализует error через метод Error()
	// - errors.As() сможет извлечь ValidationError из цепочки
	wrappedValidationErr := fmt.Errorf("проверка данных: %w", validationErr)

	// ТЕОРИЯ: Использование errors.As() для извлечения типа
	// - errors.As() проверяет цепочку ошибок
	// - Если найдена ошибка нужного типа - записывает в переменную
	// - Возвращает true если тип найден
	var extractedErr *ValidationError
	if errors.As(wrappedValidationErr, &extractedErr) {
		// ТЕОРИЯ: Получаем доступ к полям структуры
		// - extractedErr содержит исходную ошибку ValidationError
		// - Можем использовать поля для обработки ошибки
		fmt.Printf("Извлечена ошибка валидации: поле=%s, значение=%v, сообщение=%s\n",
			extractedErr.Field, extractedErr.Value, extractedErr.Message)
	}

	fmt.Println("Errors.As example completed")
}

// ExampleErrorChain демонстрирует цепочку ошибок
func ExampleErrorChain() {
	// ТЕОРИЯ: Цепочка ошибок
	// - Можно создавать цепочку: err1 -> err2 -> err3
	// - Каждая ошибка оборачивает предыдущую
	// - errors.Is() и errors.As() проверяют всю цепочку
	//
	// ПРЕИМУЩЕСТВА:
	// - Сохраняется полный контекст ошибки
	// - Можно проверить конкретную ошибку в цепочке
	// - Можно извлечь структурированную ошибку из цепочки

	// ТЕОРИЯ: Создание цепочки ошибок
	// - Каждая ошибка оборачивает предыдущую
	// - Сохраняется полный контекст ошибки
	// - Можно проверить любую ошибку в цепочке

	// Создаём цепочку из 3 ошибок
	err1 := errors.New("ошибка 1")
	err2 := fmt.Errorf("контекст 2: %w", err1)
	err3 := fmt.Errorf("контекст 3: %w", err2)

	// ТЕОРИЯ: Распаковка цепочки ошибок
	// - errors.Unwrap() извлекает ошибку на один уровень вверх
	// - Можно вызывать в цикле для распаковки всей цепочки
	fmt.Println("Распаковка цепочки ошибок:")
	currentErr := err3
	level := 1
	for currentErr != nil {
		fmt.Printf("Уровень %d: %v\n", level, currentErr)
		currentErr = errors.Unwrap(currentErr)
		level++
	}

	// ТЕОРИЯ: Проверка ошибки в цепочке
	// - errors.Is() проверяет всю цепочку
	// - Найдёт err1 даже если он обёрнут несколько раз
	if errors.Is(err3, err1) {
		fmt.Println("\nНайдена ошибка err1 в цепочке err3")
	}

	// ТЕОРИЯ: Проверка на разных уровнях
	// - Можно проверить любую ошибку в цепочке
	if errors.Is(err2, err1) {
		fmt.Println("Найдена ошибка err1 в цепочке err2")
	}

	fmt.Println("Error chain example completed")
}

