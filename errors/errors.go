// validateData имитирует валидацию данных (для примеров)
func validateData(data string) error {
	// ТЕОРИЯ: Валидация данных с обработкой ошибок
	// - Проверяем данные на различные условия
	// - Возвращаем ошибку с контекстом для каждого случая
	// - Используем fmt.Errorf для обёртывания ошибок

	// ТЕОРИЯ: Проверка на пустоту
	// - Если данные пустые - возвращаем ошибку с контекстом
	if data == "" {
		return fmt.Errorf("валидация данных: %w", errors.New("данные не могут быть пустыми"))
	}

	// ТЕОРИЯ: Проверка длины данных
	// - Если данные слишком длинные - возвращаем ошибку с контекстом
	// - Добавляем информацию о фактической и максимальной длине
	const maxLength = 100
	if len(data) > maxLength {
		return fmt.Errorf("валидация данных: %w",
			fmt.Errorf("данные слишком длинные: длина %d, максимум %d", len(data), maxLength))
	}

	return nil
}

// processData имитирует обработку данных (для примеров)
func processData(data string) error {
	// ТЕОРИЯ: Обработка данных с обёртыванием ошибок
	// - Вызываем функции и обрабатываем ошибки
	// - Оборачиваем ошибки с контекстом на каждом уровне
	// - Это создаёт цепочку ошибок с полным контекстом

	// ТЕОРИЯ: Валидация данных
	// - Вызываем validateData и проверяем ошибку
	// - Если ошибка - оборачиваем её с контекстом
	err := validateData(data)
	if err != nil {
		// ТЕОРИЯ: Оборачиваем ошибку валидации с контекстом
		// - Добавляем информацию о том, что делали
		// - Исходная ошибка сохраняется в цепочке
		return fmt.Errorf("валидация данных: %w", err)
	}

	// ТЕОРИЯ: Обработка данных
	// - Имитируем обработку данных
	// - Если возникает ошибка - оборачиваем её с контекстом
	// Имитация обработки (в реальном приложении здесь была бы реальная обработка)
	if len(data) < 3 {
		// ТЕОРИЯ: Создаём ошибку и оборачиваем с контекстом
		return fmt.Errorf("обработка данных: %w",
			errors.New("данные слишком короткие для обработки"))
	}

	return nil
}
